package pojo;

public class Concert {
    private int cno;
    private String cname;
    private String cstartime;
    private String cendtime;
    private String clocal;
    private String bname;

    public int getCno() {
        return cno;
    }

    public void setCno(int cno) {
        this.cno = cno;
    }

    public String getCname() {
        return cname;
    }

    public void setCname(String cname) {
        this.cname = cname;
    }

    public String getCstartime() {
        return cstartime;
    }

    public void setCstartime(String cstartime) {
        this.cstartime = cstartime;
    }

    public String getCendtime() {
        return cendtime;
    }

    public void setCendtime(String cendtime) {
        this.cendtime = cendtime;
    }

    public String getClocal() {
        return clocal;
    }

    public void setClocal(String clocal) {
        this.clocal = clocal;
    }

    public String getBname() {
        return bname;
    }

    public void setBname(String bname) {
        this.bname = bname;
    }
}
